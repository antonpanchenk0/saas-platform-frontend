#!/usr/bin/env node
// Generates TypeScript definitions from the backend's OpenAPI schema (drf-spectacular).
//
// Usage:
//   pnpm generate:api                 generate src/lib/api/generated/schema.d.ts
//   pnpm generate:api -- --check      fail if the committed output is out of date
//   pnpm generate:api -- --if-present exit successfully when no schema source is configured
//
// Schema source (first match wins):
//   1. API_SCHEMA_SOURCE environment variable (a file path or an http(s) URL),
//      read from the shell, .env.local, or .env
//   2. openapi/schema.yaml (or .yml / .json) in the repository root

import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputFile = resolve(rootDir, 'src/lib/api/generated/schema.d.ts')
const defaultSchemaFiles = ['openapi/schema.yaml', 'openapi/schema.yml', 'openapi/schema.json']

const BANNER = `/**
 * AUTO-GENERATED by \`pnpm generate:api\` (openapi-typescript). DO NOT EDIT.
 * Change the backend schema and regenerate instead.
 */

`

const args = new Set(process.argv.slice(2))
const checkOnly = args.has('--check')
const ifPresent = args.has('--if-present')

// Shell environment variables take precedence over values from env files.
for (const file of ['.env.local', '.env']) {
  const path = resolve(rootDir, file)
  if (existsSync(path)) process.loadEnvFile(path)
}

function fail(message) {
  console.error(`generate:api: ${message}`)
  process.exit(1)
}

function resolveSchemaSource() {
  const configured = process.env.API_SCHEMA_SOURCE?.trim()
  if (configured) {
    if (/^https?:\/\//i.test(configured)) return { label: configured, url: new URL(configured) }
    const path = resolve(rootDir, configured)
    if (!existsSync(path)) fail(`API_SCHEMA_SOURCE points to a missing file: ${path}`)
    return { label: path, url: pathToFileURL(path) }
  }

  for (const file of defaultSchemaFiles) {
    const path = resolve(rootDir, file)
    if (existsSync(path)) return { label: path, url: pathToFileURL(path) }
  }
  return undefined
}

const source = resolveSchemaSource()

if (!source) {
  if (ifPresent) {
    console.log('generate:api: no schema source configured, skipping.')
    process.exit(0)
  }
  fail(
    'no schema source configured. Set API_SCHEMA_SOURCE (file path or URL) in .env.local, ' +
      `or add one of: ${defaultSchemaFiles.join(', ')}. See README.md.`,
  )
}

let generated
try {
  // openapi-typescript validates the document and throws on an invalid schema.
  const ast = await openapiTS(source.url)
  generated = BANNER + astToString(ast)
} catch (error) {
  fail(
    `could not generate types from ${source.label}\n${error instanceof Error ? error.message : error}`,
  )
}

if (checkOnly) {
  const current = existsSync(outputFile) ? await readFile(outputFile, 'utf8') : undefined
  if (current !== generated) {
    fail('src/lib/api/generated/schema.d.ts is out of date. Run `pnpm generate:api` and commit it.')
  }
  console.log('generate:api: generated types are up to date.')
} else {
  await mkdir(dirname(outputFile), { recursive: true })
  await writeFile(outputFile, generated, 'utf8')
  console.log(`generate:api: wrote src/lib/api/generated/schema.d.ts from ${source.label}`)
}
